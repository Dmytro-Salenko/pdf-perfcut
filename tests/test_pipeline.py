def test_perfcutcontour_is_separation(processed_pdf_path):
    pdf = pikepdf.open(processed_pdf_path)
    page = pdf.pages[0]
    cs_dict = page.obj["/Resources"]["/ColorSpace"]
    found = False
    for k in cs_dict.keys():
        e = cs_dict[k]
        if isinstance(e, pikepdf.Array) and len(e) >= 2:
            if str(e[0]) == "/Separation" and str(e[1]) == "/PerfCutContour":
                found = True
                assert str(e[2]) == "/DeviceCMYK"
                c1 = e[3]["/C1"]
                assert abs(float(str(c1[0])) - 1.0) < 0.01, "C should be 1.0"
                assert abs(float(str(c1[1])) - 0.0) < 0.01, "M should be 0.0"
                assert abs(float(str(c1[2])) - 1.0) < 0.01, "Y should be 1.0"
                assert abs(float(str(c1[3])) - 0.0) < 0.01, "K should be 0.0"
    pdf.close()
    assert found, "PerfCutContour Separation not found"


def test_perfcutcontour_has_stroke_overprint(processed_pdf_path):
    """PerfCutContour must be stroked with /OP true ExtGState."""
    pdf = pikepdf.open(processed_pdf_path)
    page = pdf.pages[0]
    res = page.obj["/Resources"]

    # Find PerfCutContour CS key
    cs_dict = res["/ColorSpace"]
    pcc_cs_key = None
    for k in cs_dict.keys():
        e = cs_dict[k]
        if isinstance(e, pikepdf.Array) and len(e) >= 2:
            if str(e[0]) == "/Separation" and str(e[1]) == "/PerfCutContour":
                pcc_cs_key = str(k)
                break
    assert pcc_cs_key is not None

    # Find ExtGState with /OP true
    egs_dict = res.get("/ExtGState")
    assert egs_dict is not None, "No ExtGState in resources"
    op_gs_key = None
    for k in egs_dict.keys():
        if egs_dict[k].get("/OP") == True:  # noqa: E712
            op_gs_key = str(k)
            break
    assert op_gs_key is not None, "No ExtGState with /OP true"

    # Verify content stream applies gs before stroking PerfCutContour
    ops = list(pikepdf.parse_content_stream(page))
    current_cs = None
    gs_applied = False
    gs_before_stroke = False
    for operands, op in ops:
        name = str(op)
        if name == "gs" and str(operands[0]) == op_gs_key:
            gs_applied = True
        elif name == "CS":
            current_cs = str(operands[0])
            if current_cs != pcc_cs_key:
                gs_applied = False
        elif name in ("S", "s", "B", "b") and current_cs == pcc_cs_key and gs_applied:
            gs_before_stroke = True
        elif name == "Q":
            gs_applied = False
            current_cs = None
    pdf.close()
    assert gs_before_stroke, "PerfCutContour stroke not preceded by overprint ExtGState"


def test_page_boxes_unchanged(processed_pdf_path):
    pdf_in = pikepdf.open(INPUT_PDF)
