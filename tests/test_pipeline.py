def _spot_names(page: pikepdf.Page) -> set[str]:
    res = page.obj.get("/Resources") or {}
    cs = res.get("/ColorSpace") if res else None
    if not cs:
        return set()
    names = set()
    for k in cs.keys():
        e = cs[k]
        if isinstance(e, pikepdf.Array) and len(e) >= 2 and str(e[0]) == "/Separation":
            names.add(str(e[1]).lstrip("/"))
    return names


